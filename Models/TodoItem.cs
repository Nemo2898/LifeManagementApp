namespace LifeManagementApp.Models;

// A todo entry: the five fields required by the rubric (section 1).
// Persisted into SQLite (EF maps these properties directly).
public class TodoItem
{
    public int Id { get; set; }                       // Primary key, generated by EF
    public string Title { get; set; } = "";           // Title (empty titles are rejected)
    public int Priority { get; set; } = 3;            // 1 (highest) - 5 (lowest)
    public DateTime DueDate { get; set; } = DateTime.Today;
    public bool IsDone { get; set; }                  // Done or not
}
